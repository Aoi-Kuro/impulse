"""Writes the redrawn problem figures the site uses: course/figures/quiz1.js … quiz4.js.

    python tools/figures/export.py

Each quizN.py here draws that quiz's figures (one function per original image,
listed in its FIGURES table); this turns them into one script per quiz that
maps each image's file name to its SVG. js/figure-style.js swaps a problem's
<img> for the matching SVG while Settings › Study › Redrawn figures is on.
Re-run after changing a drawing, then check it with preview.py.

manual.py, the manual's own demo drawings, goes the same way into
course/figures/manual.js, keyed by name instead of an image file name.
"""
import importlib, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from svgkit import FONT  # noqa: E402

OUT_DIR = os.path.join(HERE, '..', '..', 'course', 'figures')
QUIZZES = (1, 2, 3, 4)
# css/style.css sets the label font once for every redrawn figure.
FONT_ATTR = f' font-family="{FONT}"'


def image_name(num):
    return 'unnamed.webp' if num == 0 else f'unnamed({num}).webp'


def export(quiz):
    """quiz: a quiz number, or 'manual' for manual.py's demo drawings."""
    numbered = isinstance(quiz, int)
    mod = importlib.import_module(f'quiz{quiz}' if numbered else quiz)
    lines, first_key = [], {}
    for num, fn, caption, _count in mod.FIGURES:
        key = image_name(num) if numbered else num
        if fn in first_key:  # same drawing as an earlier image: store it once
            lines.append(f"  F['{key}'] = F['{first_key[fn]}'];")
            continue
        first_key[fn] = key
        svg = fn().svg().replace(FONT_ATTR, '')
        assert '`' not in svg and '${' not in svg and '\\' not in svg, key
        lines.append(f"  // {caption}\n  F['{key}'] = `{svg}`;")
    body = '\n'.join(lines)
    if numbered:
        head = (f"// Redrawn figures for quiz_{quiz}, keyed by the original image's file name.\n"
                f"// Generated by tools/figures/export.py from tools/figures/quiz{quiz}.py; edit the\n"
                f"// drawings there and re-run it. Used by js/figure-style.js.\n")
        reg, name = f'quiz_{quiz}', f'quiz{quiz}'
    else:
        head = (f"// The manual's demo drawings, keyed by name (a .manual-fig-demo placeholder's\n"
                f"// data-fig is images/{quiz}/<name>); there is no original image. Generated by\n"
                f"// tools/figures/export.py from tools/figures/{quiz}.py. Used by js/manual.js.\n")
        reg, name = quiz, quiz
    js = (f"{head}(function () {{\n  const F = {{}};\n{body}\n"
          f"  (window.REDRAWN_FIGURES = window.REDRAWN_FIGURES || {{}})['{reg}'] = F;\n}})();\n")
    path = os.path.join(OUT_DIR, f'{name}.js')
    with open(path, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(js)
    return path, len(js)


if __name__ == '__main__':
    os.makedirs(OUT_DIR, exist_ok=True)
    for q in QUIZZES + ('manual',):
        path, size = export(q)
        print(f'{os.path.relpath(path, os.path.join(HERE, "..", ".."))}  {size // 1024} KB')
